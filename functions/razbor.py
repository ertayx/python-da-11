# Напиши функцию-калькулятор.

# Функция принимает:
# - первое число;
# - второе число;
# - операцию: +, -, *, /.

# Обработай:
# - деление на ноль;
# - неизвестную операцию.

# Пример 1:
# Вход:
# 10, 5, "+"

# Ожидаемый результат:
# 15

# Пример 2:
# Вход:
# 10, 5, "*"

# Ожидаемый результат:
# 50

# Пример 3:
# Вход:
# 10, 0, "/"

# Ожидаемый результат:
# Ошибка: делить на ноль нельзя

# Пример 4:
# Вход:
# 10, 5, "@"

# Ожидаемый результат:
# Ошибка: неизвестная операция


def calculator(a, b, operator):
    try:
        if operator == '+':
            return a + b
        elif operator == '-':
            return a - b
        elif operator == '*':
            return a * b
        elif operator == '/':
            return a / b
        else:
            return "Ошибка: неизвестная операция"
    except ZeroDivisionError:
        return "Ошибка: делить на ноль нельзя"
    except TypeError:
        return "Ошибка: a и b должны быть числами"

calculator(1,2, '+') # 3
calculator(7, 0, '/') # Ошибка: делить на ноль нельзя
a = int(input("num1: "))
b = int(input("num2: "))
operator = input("operator: ")
calculator(a, b, operator)