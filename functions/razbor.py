# Напиши функцию, которая принимает список чисел
# и возвращает их среднее значение.

# Учти ситуацию, когда список пустой.

# Пример 1:
# Вход:
# [5, 4, 3, 5, 5]

# Ожидаемый результат:
# 4.4

# Пример 2:
# Вход:
# []

# Ожидаемый результат:
# Ошибка: список пуст

def average_grade(numbers):
    try:
        return sum(numbers) / len(numbers)
    except ZeroDivisionError:
        return "Ошибка: список пуст"

average_grade([5, 4, 3, 5, 5])
average_grade([]) # "Ошибка: список пуст"

